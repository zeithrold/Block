#!/usr/bin/env python3
"""Run native Rust checks and retain platform evidence.

Examples:
    python scripts/verify-platform.py --platform macos-arm64
    python3 scripts/verify-platform.py --platform linux-arm64 --evidence-dir /tmp/block-arm64

Linux ARM64 requires a Linux ARM64 host; cross-compilation is not a substitute.
Visual and animation acceptance requires opening the corresponding desktop app.
Full verification refreshes repository working-file modification times (without
changing bytes) so archives with old timestamps cannot reuse stale local crates.
It preserves build caches, and checks the final binary's compile-time source ID.
"""

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess
import sys
import time


PLATFORMS = {
    "windows-amd64": ("Windows", "x86_64", "x86_64-pc-windows-msvc", "X64"),
    "linux-amd64": ("Linux", "x86_64", "x86_64-unknown-linux-gnu", "X64"),
    "linux-arm64": ("Linux", "aarch64", "aarch64-unknown-linux-gnu", "ARM64"),
    "macos-arm64": ("Darwin", "aarch64", "aarch64-apple-darwin", "ARM64"),
}


def utc_now():
    return datetime.now(timezone.utc).isoformat()


def capture(command, root, *, env=None, timeout=None):
    try:
        result = subprocess.run(
            command, cwd=root, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, encoding="utf-8", errors="replace", check=False,
            env=env, timeout=timeout,
        )
        return {"command": command, "exit_code": result.returncode, "output": result.stdout}
    except OSError as error:
        return {"command": command, "exit_code": 127, "output": str(error)}
    except subprocess.TimeoutExpired as error:
        output = error.stdout or ""
        if isinstance(output, bytes):
            output = output.decode("utf-8", errors="replace")
        return {"command": command, "exit_code": 124, "output": output + "\nCommand timed out\n"}


def source_metadata(root, evidence_dir):
    """Fingerprint working files, including untracked source and copied snapshots."""
    commands = [capture(["git", *args], root) for args in (
        ["rev-parse", "HEAD"], ["status", "--porcelain=v1", "--untracked-files=all"],
        ["ls-files", "-z", "--cached", "--others", "--exclude-standard"],
    )]
    head, status, inventory = commands
    if inventory["exit_code"] == 0:
        names = sorted(set(inventory["output"].split("\0")) - {""})
    else:
        # Remote verification may use a source archive rather than a Git checkout.
        names = []
        for directory, dirs, files in os.walk(root):
            dirs[:] = sorted(name for name in dirs if name not in {
                ".git", "target", "node_modules", "__pycache__", ".venv"
            })
            names.extend((Path(directory) / name).relative_to(root).as_posix() for name in files)
        # This ignored standalone dev-test lockfile is generated by the vendor
        # compatibility phase, and is not a workspace source input.
        names = sorted(name for name in names if name != "vendor/xattr/Cargo.lock")
    manifest = []
    for name in names:
        path = root / name
        if path == evidence_dir or evidence_dir in path.parents:
            continue
        if path.is_symlink():
            digest = hashlib.sha256(os.readlink(path).encode()).hexdigest()
            manifest.append({"path": name, "kind": "symlink", "sha256": digest})
        elif path.is_file():
            digest = hashlib.sha256()
            with path.open("rb") as source:
                for chunk in iter(lambda: source.read(1024 * 1024), b""):
                    digest.update(chunk)
            manifest.append({"path": name, "kind": "file", "sha256": digest.hexdigest()})
        else:
            manifest.append({"path": name, "kind": "missing"})
    encoded = json.dumps(manifest, ensure_ascii=False, sort_keys=True).encode()
    return {
        "revision": head["output"].strip() if head["exit_code"] == 0 else None,
        "dirty": bool(status["output"]) if status["exit_code"] == 0 else None,
        "git_status": status["output"] if status["exit_code"] == 0 else None,
        "manifest_sha256": hashlib.sha256(encoded).hexdigest(),
        "manifest": manifest, "git_commands": commands[:2],
        "inventory": "git-working-files" if inventory["exit_code"] == 0 else "source-snapshot",
    }


def native_errors(requested, rustc):
    system, arch, expected_host, runner_arch = PLATFORMS[requested]
    actual_arch = {"amd64": "x86_64", "arm64": "aarch64"}.get(
        platform.machine().lower(), platform.machine().lower()
    )
    host = next((line[6:] for line in rustc["output"].splitlines() if line.startswith("host: ")), None)
    errors = []
    if (platform.system(), actual_arch) != (system, arch):
        errors.append(f"Expected {system}/{arch}; process host is {platform.system()}/{actual_arch}")
    if rustc["exit_code"] != 0 or host != expected_host:
        errors.append(f"Expected Rust host {expected_host}; found {host!r}")
    if os.environ.get("RUNNER_ARCH") not in (None, runner_arch):
        errors.append(f"Expected RUNNER_ARCH={runner_arch}; found {os.environ['RUNNER_ARCH']}")
    if os.environ.get("CARGO_BUILD_TARGET") not in (None, "", expected_host):
        errors.append("CARGO_BUILD_TARGET selects a different target; native tests are required")
    return expected_host, errors


def verification_commands(host, requested, binary):
    # Explicit native targets override Cargo config that might cross-compile.
    # Workspace tests include core, UI, GPUI interactions, session supervision,
    # future integration tests, and documentation tests.
    commands = [
        ("format", ["cargo", "fmt", "--all", "--", "--check"]),
        ("clippy", ["cargo", "clippy", "--locked", "--workspace", "--all-targets",
                    "--all-features", "--target", host, "--", "-D", "warnings"]),
        ("tests", ["cargo", "test", "--locked", "--workspace", "--all-features", "--target", host]),
    ]
    if requested.startswith("linux-"):
        # This vendored standalone crate intentionally has no committed lockfile;
        # preserve its existing compatibility test. Workspace commands stay locked.
        commands.append(("xattr", ["cargo", "test", "--manifest-path",
                                   "vendor/xattr/Cargo.toml", "--target", host]))
    commands.append(("desktop-build", ["cargo", "build", "--locked", "-p", "block-app",
                                       "--bin", "block", "--target", host]))
    commands.append(("build-info", [str(binary), "--build-info"]))
    return commands


def run_logged(name, command, root, evidence_dir, *, env=None):
    log = evidence_dir / f"{name}.log"
    record = {"name": name, "command": command, "started_at": utc_now(), "log": log.name}
    started = time.monotonic()
    print(f"\n[{name}] {subprocess.list2cmdline(command)}", flush=True)
    with log.open("w", encoding="utf-8") as output:
        output.write(subprocess.list2cmdline(command) + "\n")
        output.flush()
        try:
            process = subprocess.Popen(command, cwd=root, stdout=subprocess.PIPE,
                                       stderr=subprocess.STDOUT, text=True, encoding="utf-8",
                                       errors="replace", bufsize=1, env=env)
            try:
                for line in process.stdout:
                    print(line, end="", flush=True)
                    output.write(line)
                    output.flush()
                record["exit_code"] = process.wait()
            except KeyboardInterrupt:
                process.terminate()
                process.wait()
                record["exit_code"] = 130
                record["interrupted"] = True
        except OSError as error:
            output.write(str(error) + "\n")
            record["exit_code"] = 127
    record.update(completed_at=utc_now(), duration_seconds=round(time.monotonic() - started, 3))
    return record


def refresh_source_mtimes(root, source, evidence_dir):
    """Refresh only this checkout's listed files; leave caches and symlinks alone."""
    root = root.resolve()
    result = {"strategy": "refresh-repository-working-files-preserve-bytes-and-cache",
              "started_at": utc_now(), "count": 0, "skipped": 0,
              "before_manifest_sha256": source["manifest_sha256"]}
    for entry in source["manifest"]:
        relative = Path(entry["path"])
        path = root / relative
        if (entry["kind"] != "file" or path.is_symlink() or not path.is_file()
                or relative.is_absolute() or ".." in relative.parts
                or any(part in {".git", "target"} for part in relative.parts)
                or relative.name == ".env" or relative.name.startswith(".env.")
                or root not in path.resolve().parents):
            result["skipped"] += 1
            continue
        # Windows Python does not implement utime(follow_symlinks=False).
        # The guards above already exclude links and paths outside this checkout.
        options = {"follow_symlinks": False} if os.utime in os.supports_follow_symlinks else {}
        os.utime(path, None, **options)
        result["count"] += 1
    refreshed = source_metadata(root, evidence_dir)
    result.update(completed_at=utc_now(), after_manifest_sha256=refreshed["manifest_sha256"])
    result["bytes_unchanged"] = source["manifest_sha256"] == refreshed["manifest_sha256"]
    return result


def desktop_binary(root, host, requested):
    # cargo metadata respects CARGO_TARGET_DIR and target-dir in Cargo config.
    result = capture(["cargo", "metadata", "--locked", "--no-deps", "--format-version", "1"], root)
    if result["exit_code"] != 0:
        raise ValueError(f"Cannot determine Cargo target directory: {result['output']}")
    directory = Path(json.loads(result["output"])["target_directory"])
    executable = "block.exe" if requested.startswith("windows-") else "block"
    return directory / host / "debug" / executable


def verify_build_info(command, root, evidence_dir, source, requested):
    started = time.monotonic()
    started_at = utc_now()
    environment = os.environ.copy()
    environment.pop("BLOCK_SOURCE_SHA256", None)
    environment.pop("BLOCK_SOURCE_COMMIT", None)
    result = capture(command, root, env=environment, timeout=20)
    record = {"name": "build-info", "command": command, "started_at": started_at,
              "process_exit_code": result["exit_code"], "exit_code": result["exit_code"],
              "log": "build-info.log"}
    (evidence_dir / record["log"]).write_text(
        subprocess.list2cmdline(command) + "\n" + result["output"], encoding="utf-8")
    errors = []
    info = None
    if result["exit_code"] == 0:
        try:
            info = json.loads(result["output"])
            expected = {
                "product_id": "one.ztd.block",
                "os": {"Windows": "windows", "Linux": "linux", "Darwin": "macos"}[PLATFORMS[requested][0]],
                "arch": PLATFORMS[requested][1],
                "source_sha256": source["manifest_sha256"],
                "source_commit": source["revision"],
            }
            for key, value in expected.items():
                if not isinstance(info, dict) or info.get(key) != value:
                    errors.append(f"Compiled {key} does not match the verified source/platform")
        except (ValueError, TypeError):
            errors.append("Binary did not return valid build-info JSON")
    if info is not None:
        (evidence_dir / "build-info.json").write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")
        record["build_info_file"] = "build-info.json"
    if errors:
        record["exit_code"] = 1
    binary = Path(command[0])
    if binary.is_file():
        with binary.open("rb") as executable:
            record["binary_sha256"] = hashlib.file_digest(executable, "sha256").hexdigest()
    record.update(validation_errors=errors, completed_at=utc_now(),
                  duration_seconds=round(time.monotonic() - started, 3))
    print(f"\n[build-info] exit {record['exit_code']} " + "; ".join(errors), flush=True)
    return record


def finish_source_audit(root, evidence_dir, report, exit_code):
    final = source_metadata(root, evidence_dir)
    report["source_final"] = {key: final[key] for key in (
        "manifest_sha256", "revision", "dirty", "inventory"
    )}
    changes = [key for key in ("manifest_sha256", "revision")
               if final[key] != report["source"][key]]
    report["source_changed_during_run"] = bool(changes)
    if changes:
        report["source_consistency_errors"] = [f"Source {key} changed during verification" for key in changes]
        print("\n".join(report["source_consistency_errors"]), file=sys.stderr)
        if exit_code == 0:
            report["status"] = "source-changed-during-run"
            return 1
    return exit_code


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--platform", choices=PLATFORMS, required=True)
    parser.add_argument("--evidence-dir", type=Path, help="New directory for logs and report; preserves target caches")
    parser.add_argument("--verify-host-only", action="store_true", help="Validate host only; does not run tests")
    parser.add_argument("--dry-run", action="store_true", help="Record a plan only; does not claim test success")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    evidence_dir = (args.evidence_dir or root / "target" / "platform-verification" /
                    f"{args.platform}-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')}").resolve()
    if evidence_dir.exists() and any(evidence_dir.iterdir()):
        parser.error(f"Evidence directory is not empty: {evidence_dir}; choose a new directory")
    report = {
        "schema_version": 2, "requested_platform": args.platform, "started_at": utc_now(),
        "platform": {"system": platform.system(), "machine": platform.machine(),
                     "release": platform.release(), "runner_arch": os.environ.get("RUNNER_ARCH")},
        "source": source_metadata(root, evidence_dir),
        "rustc": capture(["rustc", "-vV"], root),
        "commands": [], "status": "running",
        "scope": "native-build-and-automated-tests; visual-and-animation-acceptance-is-separate",
    }
    evidence_dir.mkdir(parents=True, exist_ok=True)
    report_file = evidence_dir / "report.json"

    def save():
        report_file.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    host, errors = native_errors(args.platform, report["rustc"])
    report.update(rust_host=host, host_errors=errors)
    plan = []
    setup_error = None
    if not errors and not args.verify_host_only:
        try:
            binary = desktop_binary(root, host, args.platform)
            report["desktop_binary"] = str(binary)
            plan = verification_commands(host, args.platform, binary)
        except (ValueError, KeyError, TypeError) as error:
            setup_error = str(error)
    report["planned_commands"] = [{"name": name, "command": command} for name, command in plan]
    report["build_environment"] = {
        "BLOCK_SOURCE_SHA256": report["source"]["manifest_sha256"],
        "BLOCK_SOURCE_COMMIT": report["source"]["revision"],
    }
    save()
    exit_code = 0
    if errors:
        report["status"] = "host-mismatch"
        print("\n".join(errors), file=sys.stderr)
        exit_code = 1
    elif setup_error:
        report.update(status="configuration-error", configuration_error=setup_error)
        print(setup_error, file=sys.stderr)
        exit_code = 1
    elif args.verify_host_only:
        report["status"] = "host-verified-only"
    elif args.dry_run:
        report["commands"] = [{"name": name, "command": command, "exit_code": None}
                              for name, command in plan]
        report["status"] = "planned-only"
    else:
        report["source_refresh"] = refresh_source_mtimes(root, report["source"], evidence_dir)
        if not report["source_refresh"]["bytes_unchanged"]:
            report["configuration_error"] = "Source bytes changed while refreshing timestamps; run against a stable source snapshot"
            exit_code = 1
        else:
            cargo_environment = os.environ.copy()
            for key, value in report["build_environment"].items():
                if value is None:
                    cargo_environment.pop(key, None)
                else:
                    cargo_environment[key] = value
            for name, command in plan:
                if name == "build-info":
                    record = verify_build_info(command, root, evidence_dir, report["source"], args.platform)
                else:
                    record = run_logged(name, command, root, evidence_dir, env=cargo_environment)
                report["commands"].append(record)
                save()
                if record["exit_code"] != 0:
                    exit_code = record["exit_code"] if record["exit_code"] > 0 else 1
                    break
        report["status"] = "passed" if exit_code == 0 else "failed"
        exit_code = finish_source_audit(root, evidence_dir, report, exit_code)
    report.update(completed_at=utc_now(), exit_code=exit_code)
    save()
    print(f"\n{report['status']}: {report_file}", flush=True)
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
